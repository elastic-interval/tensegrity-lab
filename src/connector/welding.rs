//! The welding document: what is welded, how much seam, and an estimate of
//! the work and its cost, for the welding shop and for budgeting. Counts come
//! from the parts list; the rates and minutes are assumptions, all here.

use crate::connector::fork::{BOSS_ARM_RADIUS, TUBE_BORE_RADIUS, TUBE_LENGTH, TUBE_RADIUS};
use crate::connector::parts::{parts_list, placements, Part, STEEL_DENSITY};
use crate::connector::strut::{OUTER_BORE_RADIUS, OUTER_RADIUS};
use crate::fabric::interval::Role;
use crate::fabric::Fabric;
use crate::units::{Grams, Meters, Seconds, Unit, MM_PER_METER};
use std::f32::consts::PI;
use std::fmt::Write;

/// The strut cap: a tapped disc welded on the end of a short steel tube, 40×3
/// like the strut's outer tube (`docs/parts.md`).
const CAP_DISC_DIAMETER: Meters = Meters(0.036);
const CAP_TUBE_LENGTH: Meters = Meters(0.040);

/// Workshop rate in euros an hour, a Dutch metalwork shop's going rate.
const RATE: f32 = 65.0;
/// Each piece of work, in series with a fixture, handling included.
const CUT_CROSS_TUBE: Seconds = minutes(1.0);
const CUT_CAP_TUBE: Seconds = minutes(1.5);
const WELD_RING_TUBE: Seconds = minutes(4.0);
const WELD_DISC_TUBE: Seconds = minutes(6.0);
const WELD_CAP: Seconds = minutes(5.0);
/// Making the two fixtures, then setting up and checking first pieces.
const RING_FIXTURE: Seconds = hours(6.0);
const CAP_FIXTURE: Seconds = hours(3.0);
const SETUP: Seconds = hours(4.0);
/// Wire, gas and grinding discs, as a share of the labour.
const CONSUMABLES: f32 = 0.05;
/// Hot-dip galvanizing: euros a kilogram, and the smallest charge for a batch.
const GALVANIZING_PER_KG: f32 = 1.5;
const GALVANIZING_MINIMUM: f32 = 200.0;

const MM: f32 = MM_PER_METER;

const fn minutes(count: f32) -> Seconds {
    Seconds(count * 60.0)
}

const fn hours(count: f32) -> Seconds {
    Seconds(count * 3600.0)
}

fn in_minutes(time: Seconds) -> f32 {
    time.f32() / 60.0
}

fn in_hours(time: Seconds) -> f32 {
    time.f32() / 3600.0
}

/// `count` pieces of work, each `each` long.
fn times(count: usize, each: Seconds) -> Seconds {
    Seconds(count as f32 * each.f32())
}

/// The document for `fabric`, with its connectors committed.
pub fn document(fabric: &Fabric) -> String {
    let connector = fabric.connector.as_ref().expect("fabric has connectors");
    let dimensions = &connector.dimensions;
    let ring_radius = fabric.dimensions.push_radius.f32();
    let list = parts_list(&placements(fabric));
    let rings = list.get(&Part::Ring).copied().unwrap_or(0);
    let discs: Vec<(Part, usize)> =
        list.iter().filter(|(part, _)| matches!(part, Part::CustomDisc(_))).map(|(p, n)| (*p, *n)).collect();
    let disc_tubes: usize = discs
        .iter()
        .map(|(part, n)| match part {
            Part::CustomDisc(shape) => shape.count as usize * n,
            _ => 0,
        })
        .sum();
    let caps = 2 * fabric.intervals.values().filter(|i| i.has_role(Role::Pushing)).count();

    let boss_width = 2.0 * BOSS_ARM_RADIUS.f32() * MM;
    let plate = dimensions.ring_thickness.f32() * MM;
    let tube_seam = 2.0 * boss_width;
    let cap_seam = PI * CAP_DISC_DIAMETER.to_mm();
    let disc_volume = PI * (CAP_DISC_DIAMETER.f32() / 2.0).powi(2) * dimensions.cap_thickness.f32();
    let tube_volume = PI * (OUTER_RADIUS.f32().powi(2) - OUTER_BORE_RADIUS.f32().powi(2)) * CAP_TUBE_LENGTH.f32();
    let cap_mass = STEEL_DENSITY.mass(disc_volume + tube_volume);
    let ring_mass = Part::Ring.mass(ring_radius, dimensions);
    let disc_mass = discs.iter().fold(Grams(0.0), |total, (part, n)| total + part.mass(ring_radius, dimensions) * *n as f32);
    let steel = (ring_mass * rings as f32 + disc_mass + cap_mass * caps as f32).to_kg();
    let cross_tubes = rings + disc_tubes;

    let mut doc = String::new();
    let w = &mut doc;
    let date = chrono::Local::now().format("%Y-%m-%d");
    writeln!(w, "# {}: welding\n", fabric.name).unwrap();
    writeln!(w, "Generated by tensegrity-lab on {date} from the current plan. Counts follow the plan; the minutes,").unwrap();
    writeln!(w, "rates and prices are assumptions, listed under Estimate. **Nothing here has been checked by the engineer").unwrap();
    writeln!(w, "or quoted by a welder.** Everything else in the hardware is laser cut, cut to length or bought.\n").unwrap();

    w.push_str("## What is welded\n\n");
    w.push_str("| Qty | Assembly | Joint | Seam each | Seam in all |\n|---:|---|---|---:|---:|\n");
    writeln!(
        w,
        "| {rings} | Ring with boss and cross-tube | cross-tube across the boss's end | {tube_seam:.0} mm | {:.1} m |",
        rings as f32 * tube_seam / MM
    )
    .unwrap();
    for (part, n) in &discs {
        if let Part::CustomDisc(shape) = part {
            let count = shape.count as f32;
            writeln!(
                w,
                "| {n} | {} | {} cross-tubes, one per boss | {:.0} mm | {:.1} m |",
                part.name(),
                shape.count,
                count * tube_seam,
                *n as f32 * count * tube_seam / MM
            )
            .unwrap();
        }
    }
    writeln!(
        w,
        "| {caps} | Strut cap | tapped disc on a tube end, all round | {cap_seam:.0} mm | {:.1} m |\n",
        caps as f32 * cap_seam / MM
    )
    .unwrap();
    writeln!(w, "About {steel:.0} kg of steel to galvanize after welding.\n").unwrap();

    w.push_str("## The joints\n\n### Cross-tube on a ring or disc\n\n");
    writeln!(
        w,
        "- Tube: {:.1} × {:.1} mm (DN10, EN 10220), cut {:.1} mm long and deburred, {cross_tubes} pieces.",
        TUBE_RADIUS.to_mm() * 2.0,
        TUBE_RADIUS.to_mm() - TUBE_BORE_RADIUS.to_mm(),
        TUBE_LENGTH.to_mm()
    )
    .unwrap();
    writeln!(
        w,
        "- It lies across the end of the boss ({boss_width:.0} mm wide, {plate:.0} mm plate), its axis square to the bolt and to"
    )
    .unwrap();
    writeln!(w, "  the boss, the boss's end seated 1 mm into its wall.").unwrap();
    writeln!(
        w,
        "- Two fillet seams, one on each face of the plate, each along the boss's {boss_width:.0} mm width. Throat for the"
    )
    .unwrap();
    w.push_str("  engineer to set; 3 mm is a guess that suits the 3.2 mm wall without burning through.\n");
    writeln!(
        w,
        "- The bore must stay round and clean: it takes the terminal's 9.7 mm pin in a {:.1} mm bore once galvanized.",
        TUBE_BORE_RADIUS.to_mm() * 2.0
    )
    .unwrap();
    w.push_str("- The ring's faces must stay flat: it turns on the bolt between POM washers.\n");
    w.push_str("- A fixture holds ring and tube: a pin through the bore at the pivot, a peg in the bolt hole. The\n");
    w.push_str("  custom discs are one-offs, set out by hand, and their bosses' angles matter to the degree.\n\n");

    w.push_str("### Strut cap\n\n");
    writeln!(
        w,
        "- A Ø{:.0} × {:.0} mm disc, tapped M12, on the end of a 40×3 mm steel tube {:.0} mm long, {caps} pieces.",
        CAP_DISC_DIAMETER.to_mm(),
        dimensions.cap_thickness.to_mm(),
        CAP_TUBE_LENGTH.to_mm()
    )
    .unwrap();
    writeln!(w, "- One fillet seam all round, about {cap_seam:.0} mm. The disc must sit square to the tube: the stack of rings").unwrap();
    w.push_str("  stands on it.\n");
    w.push_str("- Tap or chase the M12 thread after galvanizing, or it will not take the bolt.\n\n");

    let labour = [
        ("Cut cross-tubes", times(cross_tubes, CUT_CROSS_TUBE), format!("{cross_tubes} × {} min", in_minutes(CUT_CROSS_TUBE))),
        ("Cut cap tubes", times(caps, CUT_CAP_TUBE), format!("{caps} × {} min", in_minutes(CUT_CAP_TUBE))),
        ("Weld ring cross-tubes", times(rings, WELD_RING_TUBE), format!("{rings} × {} min", in_minutes(WELD_RING_TUBE))),
        ("Weld disc cross-tubes", times(disc_tubes, WELD_DISC_TUBE), format!("{disc_tubes} × {} min", in_minutes(WELD_DISC_TUBE))),
        ("Weld caps", times(caps, WELD_CAP), format!("{caps} × {} min", in_minutes(WELD_CAP))),
        (
            "Fixtures",
            Seconds(RING_FIXTURE.f32() + CAP_FIXTURE.f32()),
            format!("ring {} h, cap {} h", in_hours(RING_FIXTURE), in_hours(CAP_FIXTURE)),
        ),
        ("Setting up, first pieces checked", SETUP, format!("{} h", in_hours(SETUP))),
    ];
    let hours: f32 = labour.iter().map(|(_, time, _)| in_hours(*time)).sum();
    let consumables = hours * RATE * CONSUMABLES;
    let galvanizing = (steel * GALVANIZING_PER_KG).max(GALVANIZING_MINIMUM);
    w.push_str("## Estimate\n\n| Work | Basis | Hours | € |\n|---|---|---:|---:|\n");
    for (work, time, basis) in &labour {
        let h = in_hours(*time);
        writeln!(w, "| {work} | {basis} | {h:.1} | {:.0} |", h * RATE).unwrap();
    }
    writeln!(w, "| Consumables | {:.0} % of labour | | {consumables:.0} |", CONSUMABLES * 100.0).unwrap();
    writeln!(
        w,
        "| Hot-dip galvanizing | {steel:.0} kg at €{GALVANIZING_PER_KG:.2}/kg, at least €{GALVANIZING_MINIMUM:.0} | | {galvanizing:.0} |"
    )
    .unwrap();
    writeln!(w, "| **Total** | | **{hours:.0}** | **{:.0}** |\n", hours * RATE + consumables + galvanizing).unwrap();
    writeln!(
        w,
        "At €{RATE:.0} an hour, excluding VAT, the tube and plate stock, and the laser cutting (see the DXFs). Take it as"
    )
    .unwrap();
    w.push_str("good to about half again either way until a shop quotes. The minutes are for series work in a fixture;\n");
    w.push_str("they and the rates are constants in `src/connector/welding.rs`.\n\n");

    w.push_str("## To ask the welder\n\n");
    w.push_str("- TIG or MIG for the cross-tubes, and the throat they would choose on 3.2 mm tube and 5 mm plate.\n");
    writeln!(w, "- Whether they galvanize themselves or send it out, and how they hang {} small parts.", cross_tubes - disc_tubes + discs.len() + caps).unwrap();
    w.push_str("- Whether the cap is better turned from solid bar than welded.\n");
    doc
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::build::dsl::fabric_library::{self, FabricName};
    use crate::build::dsl::fabric_plan_executor::FabricPlanExecutor;

    fn built_headless_hug() -> Fabric {
        let mut executor = FabricPlanExecutor::new(fabric_library::get_fabric_plan(FabricName::HeadlessHug));
        while !executor.is_complete() {
            let _ = executor.iterate();
        }
        let mut fabric = executor.fabric;
        fabric.update_all_attachment_connections();
        fabric
    }

    /// Writes `HeadlessHug-welding-<date>.md` to the working directory:
    ///
    /// ```
    /// cargo test --release --lib export_headless_hug_welding -- --ignored
    /// ```
    #[test]
    #[ignore]
    fn export_headless_hug_welding() {
        let filename = format!("HeadlessHug-welding-{}.md", chrono::Local::now().format("%Y-%m-%d"));
        std::fs::write(&filename, document(&built_headless_hug())).expect("write document");
        println!("{filename}");
    }
}
